#!/usr/bin/env node
// Writes src/lib-texts.generated.ts: every lib/<profile>/*.h as a string, so the
// package needs no bundler feature (import.meta.glob, ?raw) and no fs at runtime.
// Runs before build and test; the output is not committed.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

const root = new URL('../', import.meta.url)
const out = {}
for (const profile of ['std', 'puny']) {
  const dir = new URL(`lib/${profile}/`, root)
  out[profile] = Object.fromEntries(
    readdirSync(dir)
      .filter(f => f.endsWith('.h'))
      .sort()
      .map(f => [f, readFileSync(new URL(f, dir), 'utf8')]),
  )
}
const body =
  '// GENERATED by scripts/gen-lib-texts.mjs from lib/ — do not edit.\n'
  + '// Library texts: Inform 6 Standard Library (Artistic 2.0), PunyInform (MIT),\n'
  + '// exits.h (MIT). See lib/*/LICENSE-*.\n'
  + `export const LIB_TEXTS: Record<'std' | 'puny', Record<string, string>> = ${JSON.stringify(out)}\n`
writeFileSync(new URL('src/lib-texts.generated.ts', root), body)
console.log(`gen-lib-texts: std ${Object.keys(out.std).length} files, puny ${Object.keys(out.puny).length} files`)

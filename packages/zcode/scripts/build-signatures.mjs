#!/usr/bin/env node
// Builds src/veneer-signatures.generated.ts: the shape of each of Inform's veneer routines
// (Main__, RT__Err, CA__Pr, …), from the debug fixtures, which name them. A veneer routine is
// one the .dbg gives no source location: the compiler wrote it, not the game or its library.
//
// A shape is a routine's locals count and its opcodes (see routineShape in src/fingerprint.ts).
// One that two different veneer names share, or that a non-veneer routine also has, names
// nothing, so it is left out: fingerprinting must never put a veneer name on game code.
//
//   pnpm build && node scripts/build-signatures.mjs   (after `pnpm fixtures`)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { parseStory, readSymbols } from '../dist/index.js'
import { routineShape, shapeHash } from '../dist/fingerprint.js'

const FIX = fileURLToPath(new URL('../test/.fixtures/', import.meta.url))
const OUT = fileURLToPath(new URL('../src/veneer-signatures.generated.ts', import.meta.url))

const veneer = new Map() // hash → Set of names
const other = new Set() // hashes of routines with a source location
const fixtures = readdirSync(FIX).filter(f => f.endsWith('.dbg')).sort()
for (const dbg of fixtures) {
  const storyFile = readdirSync(FIX).find(f => f.startsWith(dbg.replace(/\.dbg$/, '.z')))
  const story = parseStory(new Uint8Array(readFileSync(FIX + storyFile)))
  const symbols = readSymbols(readFileSync(FIX + dbg, 'utf8'))
  for (const r of story.code.routines) {
    const sym = symbols.routines[r.address]
    const hash = shapeHash(routineShape(r))
    if (sym && !sym.location && sym.name !== 'Main__') {
      if (!veneer.has(hash)) veneer.set(hash, new Set())
      veneer.get(hash).add(sym.name)
    } else other.add(hash)
  }
}

const entries = [...veneer]
  .filter(([hash, names]) => names.size === 1 && !other.has(hash))
  .map(([hash, names]) => [hash, [...names][0]])
  .sort((a, b) => (a[1] < b[1] ? -1 : a[1] > b[1] ? 1 : a[0] < b[0] ? -1 : 1))
const dropped = [...veneer].filter(([hash, names]) => names.size > 1 || other.has(hash)).map(([, n]) => [...n].join('/'))

writeFileSync(OUT, `// Generated by scripts/build-signatures.mjs from the debug fixtures (${fixtures.length} .dbg files). Do not edit.
// Each key is shapeHash(routineShape(r)) of one of Inform 6.44's veneer routines; the value its name.
export const VENEER: Record<string, string> = {
${entries.map(([h, n]) => `  '${h}': '${n}',`).join('\n')}
}
`)
console.log(`${entries.length} shapes for ${new Set(entries.map(e => e[1])).size} veneer routines${dropped.length ? `; left out (shared): ${dropped.join(', ')}` : ''}`)

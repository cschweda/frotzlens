#!/usr/bin/env node
// Builds src/inform/library.generated.ts: what each library (the Standard Library and PunyInform,
// as @frotzinc/inform6-wasm has them) puts in a story by itself, from an empty game compiled with
// it. The decompiler compares a story with this to write only what the game added: its own verbs
// and lines (as Verb and Extend), and the library routines it replaced (as Replace).
//
//   pnpm build && node scripts/build-library.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from '@frotzinc/inform6-wasm'
import { parseStory, readSymbols } from '../dist/index.js'
import { informLine } from '../dist/inform/grammar.js'

const OUT = fileURLToPath(new URL('../src/inform/library.generated.ts', import.meta.url))

const SKELETONS = {
  std: `Constant Story "S";
Constant Headline "^H^";
Include "Parser";
Include "VerbLib";
Object Room "Room" has light;
[ Initialise; location = Room; ];
Include "Grammar";
`,
  puny: `!% -~S
!% $OMIT_UNUSED_ROUTINES=1
Constant Story "S";
Constant Headline "^H^";
Constant INITIAL_LOCATION_VALUE = Room;
Include "globals.h";
Include "puny.h";
Object Room "Room" has light;
[ Initialise; ];
`,
}

// Entry points the library stubs out (`Stub DeathMessage 0;`): a game that defines one isn't
// replacing a library routine, so these aren't counted as the library's.
const LIB = join(dirname(createRequire(import.meta.url).resolve('@frotzinc/inform6-wasm/package.json')), 'lib')
// So are the defaults it gives only when the game has none (`#Ifndef PrintRank; [ PrintRank; ... ];`).
const stubs = id =>
  new Set(
    readdirSync(join(LIB, id)).flatMap(f => {
      const text = readFileSync(join(LIB, id, f), 'latin1')
      return [...text.matchAll(/^\s*Stub\s+(\w+)/gm), ...text.matchAll(/#Ifndef\s+(\w+)\s*;\s*\[\s*(\w+)/gi)]
        .filter(m => !m[2] || m[2].toLowerCase() === m[1].toLowerCase())
        .map(m => m[1].toLowerCase())
    }),
  )

const libraries = {}
for (const [id, source] of Object.entries(SKELETONS)) {
  const out = await compile(source, { version: 'z5', library: id, debug: true })
  if (!out.ok) throw new Error(`The ${id} skeleton didn't compile:\n${out.rawOutput}`)
  const story = parseStory(out.story)
  const sym = readSymbols(out.dbg)
  const names = {
    routine: a => sym.routines[a]?.name,
    action: n => sym.actions[n] ?? `action_${n}`,
    attribute: n => sym.attributes[n] ?? `attr_${n}`,
  }
  const verbs = story.grammar.verbs.map(v => ({
    words: v.words,
    meta: v.words.some(w => story.dictionary.entries.find(e => e.word === w)?.inform?.meta),
    lines: v.lines.map(l => informLine(story, l, names) ?? '?'),
  }))
  const stubbed = stubs(id)
  const routines = [...new Set(Object.values(sym.routines).filter(r => r.location && r.location.file !== 0 && !r.artificial && !stubbed.has(r.name.toLowerCase())).map(r => r.name))].sort()
  const individuals = Object.entries(sym.properties).filter(([n]) => Number(n) >= 64).map(([, name]) => name).sort()
  libraries[id] = { verbs, routines, individuals }
}

const body = `// Generated by scripts/build-library.mjs from an empty game compiled with each library. Do not edit.
// Each library's verbs (their words, whether meta, and their lines as Inform writes them), and the
// names of its routines and individual properties.
export interface LibraryVerb { words: string[]; meta: boolean; lines: string[] }
export interface Library { verbs: LibraryVerb[]; routines: string[]; individuals: string[] }
export const LIBRARIES: Record<'std' | 'puny', Library> = ${JSON.stringify(libraries, null, 2)}
`
writeFileSync(OUT, body)
console.log(Object.entries(libraries).map(([k, v]) => `${k}: ${v.verbs.length} verbs, ${v.routines.length} routines`).join('; '))
